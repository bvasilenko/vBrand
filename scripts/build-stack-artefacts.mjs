import fs from 'node:fs';
import path from 'node:path';
import React from 'react';
import { getStackRuntime } from '../dist/stacks.js';

const OUT_DIR = path.resolve('dist/stacks');
const DEMO_OUT_DIR = path.resolve('examples/demo/public/stacks');
const STACKS = ['vite', 'next', 'astro'];

function previewComposition(stack) {
  return React.createElement(
    'main',
    { 'data-vbrand-stack-preview-fixture': stack },
    React.createElement('h1', null, 'vBrand stack preview artefact'),
    React.createElement('p', null, `Generated by ${stack} StackRuntime.bootstrapMarkup.`),
    React.createElement('section', { 'data-island': 'vbrand-preview-island' }, 'Shared island preview content'),
  );
}

fs.mkdirSync(OUT_DIR, { recursive: true });
fs.mkdirSync(DEMO_OUT_DIR, { recursive: true });
for (const stack of STACKS) {
  const html = getStackRuntime(stack).bootstrapMarkup(previewComposition(stack));
  fs.writeFileSync(path.join(OUT_DIR, `${stack}.html`), html);
  fs.writeFileSync(path.join(DEMO_OUT_DIR, `${stack}.html`), html);
}
process.stdout.write(`Stack artefacts written to ${OUT_DIR} and ${DEMO_OUT_DIR}\n`);
